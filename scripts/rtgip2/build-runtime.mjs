// Deterministic build of supabase/functions/_shared/rtgip2-runtime.bundle.js from the runtime
// source. `node scripts/rtgip2/build-runtime.mjs` writes it; `--check` fails when it is stale;
// `--out <file>` writes the build somewhere else (the reproducibility test builds twice that way).
// The runtime bundle carries the rtgip/3 modules (src/lib/rooftopos-parked/rtgip3/) through runtime.ts.
// Its sha256 is printed and written beside it as rtgip2-runtime.bundle.js.sha256: that digest is the
// rtgip/3-attest/1 `verifier` (the app secret RTGIP3_VERIFIER_DIGEST, counterpart of the Gateway's).
// The esbuild it is built with is recorded per app in the runtime's PROVENANCE.json (bundle.esbuild).
import { build, version as ESBUILD_VERSION } from "esbuild";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
export const ENTRY = "src/lib/rooftopos-parked/rtgip2-autolabels/runtime-entry.ts";
export const OUTFILE = path.join(ROOT, "supabase/functions/_shared/rtgip2-runtime.bundle.js");
export const SHA_SUFFIX = ".sha256";
export const bundleSha256 = (text) => createHash("sha256").update(text, "utf8").digest("hex");
export const shaLine = (text, file) => `${bundleSha256(text)}  ${path.basename(file)}\n`;
export const POSTGRES_SPECIFIER = "npm:postgres@3.4.5";
// The production Gateway origin (src/lib/rooftopos-parked/rtgip2-autolabels/runtime-config.ts). Unset,
// the bundle keeps the .invalid placeholder and refuses every dispatch. Set, it must be a bare https
// origin; the bundle sha256 (RTGIP3_VERIFIER_DIGEST) then changes with it.
export const GATEWAY_ORIGIN_VAR = "RTGIP_PRODUCTION_GATEWAY_ORIGIN";
export function gatewayOriginDefine(value = process.env[GATEWAY_ORIGIN_VAR]) {
  if (value === undefined || value === "") return {};
  const u = new URL(value);
  if (u.protocol !== "https:" || u.username || u.password || u.origin !== value || u.hostname.endsWith(".invalid"))
    throw new Error(`${GATEWAY_ORIGIN_VAR} must be a bare https origin, got ${JSON.stringify(value)}`);
  return { __RTGIP_PRODUCTION_GATEWAY_ORIGIN__: JSON.stringify(value) };
}

const plugin = {
  name: "rtgip2-runtime",
  setup(b) {
    b.onResolve({ filter: /^postgres$/ }, () => ({ path: POSTGRES_SPECIFIER, external: true }));
    b.onResolve({ filter: /^@\// }, (args) =>
      b.resolve(path.join(ROOT, "src", args.path.slice(2)), { kind: args.kind, resolveDir: ROOT }),
    );
  },
};

export async function buildRuntime(entry = ENTRY) {
  const r = await build({
    absWorkingDir: ROOT,
    entryPoints: [entry],
    bundle: true,
    write: false,
    format: "esm",
    platform: "neutral",
    target: "es2022",
    charset: "utf8",
    legalComments: "none",
    sourcemap: false,
    minify: false,
    logLevel: "silent",
    plugins: [plugin],
    define: gatewayOriginDefine(),
    banner: { js: "// Generated by scripts/rtgip2/build-runtime.mjs from the rtgip2 runtime source. Do not edit." },
  });
  if (r.outputFiles.length !== 1) throw new Error("expected one output file");
  return r.outputFiles[0].text;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const outfile = OUTFILE;
  const text = await buildRuntime(ENTRY);
  const sidecar = true;
  if (process.argv.includes("--check")) {
    const stale =
      !existsSync(outfile) ||
      readFileSync(outfile, "utf8") !== text ||
      (sidecar && (!existsSync(outfile + SHA_SUFFIX) || readFileSync(outfile + SHA_SUFFIX, "utf8") !== shaLine(text, outfile)));
    if (stale) {
      console.error(`${path.basename(outfile)} is stale: run node scripts/rtgip2/build-runtime.mjs`);
      process.exit(1);
    }
  } else {
    const at = process.argv.indexOf("--out");
    const target = at > 0 ? path.resolve(process.argv[at + 1]) : outfile;
    writeFileSync(target, text);
    if (sidecar) writeFileSync(target + SHA_SUFFIX, shaLine(text, target));
  }
  console.log(`${path.basename(outfile)} sha256 ${bundleSha256(text)} (esbuild ${ESBUILD_VERSION}, gateway origin ${process.env[GATEWAY_ORIGIN_VAR] || "placeholder"})`);
}
