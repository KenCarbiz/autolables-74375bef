// Regenerates docs/admin-v3/ADMIN-SCREEN-COVERAGE.md and ADMIN-ROUTE-REDIRECTS.md
// from the category model, so the registers can never drift from the code.
// Run: npx vite-node scripts/admin-v3/registers.ts
import { writeFileSync } from "node:fs";
import { ADMIN_CATEGORIES, CATALOG_DISPOSITIONS, TABS_OUTSIDE_CATEGORIES, rowHref } from "@/lib/admin/categories";
import { LEGACY_TAB_REDIRECTS, legacyAliasTable, resolveAdminTab, ADMIN_SECTIONS } from "@/lib/admin/sections";

const rows = ADMIN_CATEGORIES.flatMap((c) => c.groups.flatMap((g) => g.rows.map((r) => ({ c, g, r }))));
const byKey = new Map(rows.map((x) => [x.r.key, x]));

const cov: string[] = [
  "# ADMIN-SCREEN-COVERAGE",
  "",
  "Generated by `scripts/admin-v3/registers.ts` from `src/lib/admin/categories.ts`. Every one of the 123 handoff catalog ids appears exactly once (enforced by `categories.test.ts`).",
  "",
  "Dispositions: **implemented** = new V3 surface in this change; **reused** = existing editor or child route, re-homed under its category; **in-editor** = a dialog/detail state inside that editor; **shared-component** = reusable state; **external** = another rail destination or service; **platform-only**; **verify** = V item, see ADMIN-VERIFICATION-REGISTER.md.",
  "",
  "Scope of this change: the navigation, directory, category pages, breadcrumbs, search, redirects and V3 tokens are new. The child editors keep their current internals (same keys, writers and permissions); restyling each editor's interior to V3 and collapsing the duplicate writers listed in ADMIN-SETTINGS-TRACEABILITY.md §5 are follow-up batches.",
  "",
  "| ID | Screen | Disposition | Category | Destination | Note |",
  "|---|---|---|---|---|---|",
];
const counts: Record<string, number> = {};
for (const e of CATALOG_DISPOSITIONS) {
  counts[e.disposition] = (counts[e.disposition] ?? 0) + 1;
  const loc = byKey.get(e.target);
  const dest = loc ? `\`${rowHref(loc.r)}\` (${loc.r.title})` : `\`${e.target}\``;
  cov.push(`| ${e.id} | ${e.title} | ${e.disposition} | ${loc?.c.label ?? "—"} | ${dest} | ${e.note ?? ""} |`);
}
cov.push("", "## Totals", "", ...Object.entries(counts).map(([k, v]) => `- ${k}: ${v}`), `- total: ${CATALOG_DISPOSITIONS.length}`);
writeFileSync("docs/admin-v3/ADMIN-SCREEN-COVERAGE.md", cov.join("\n") + "\n");

const red: string[] = [
  "# ADMIN-ROUTE-REDIRECTS",
  "",
  "Generated by `scripts/admin-v3/registers.ts`. Old `?tab=` links keep working: the page resolves canonical ids and legacy aliases exactly as before (`resolveAdminLocation`), keeps any `&panel=` anchor, and re-checks the viewer's capability on every load, so a refreshed or shared link never widens access. Child routes (`/admin/...`) are unchanged.",
  "",
  "## New V3 entry points",
  "",
  "| URL | Shows |",
  "|---|---|",
  "| `/admin` | Settings directory (search + eight categories). Previously opened the Overview tab. |",
  ...ADMIN_CATEGORIES.map((c) => `| \`/admin?category=${c.id}\` | ${c.label} category page |`),
  "| `/admin?tab=overview` | Setup checklist (former Overview), linked from the directory |",
  "",
  "## Legacy `?tab=` ids",
  "",
  "| Old link | Resolves to | Category / setting | Verified by |",
  "|---|---|---|---|",
];
for (const r of legacyAliasTable()) {
  if (r.redirect) { red.push(`| \`/admin?tab=${r.legacy}\` | redirect \`${r.redirect}\` | outside Administration | sections.test.ts |`); continue; }
  const loc = rows.find((x) => x.r.tab === r.tab);
  red.push(`| \`/admin?tab=${r.legacy}\` | \`/admin?tab=${r.tab}\` | ${loc ? `${loc.c.label} / ${loc.r.title}` : TABS_OUTSIDE_CATEGORIES[r.tab ?? ""] ?? "—"} | sections.test.ts, categories.test.ts |`);
}
red.push("", "## V2 canonical `?tab=` ids", "", "| Tab | Category / setting |", "|---|---|");
for (const s of ADMIN_SECTIONS) for (const t of s.tabs) {
  const loc = rows.find((x) => x.r.tab === t.id);
  const redirect = LEGACY_TAB_REDIRECTS[t.id];
  red.push(`| \`${t.id}\` | ${redirect ? `redirect \`${redirect}\`` : loc ? `${loc.c.label} / ${loc.r.title}` : TABS_OUTSIDE_CATEGORIES[t.id] ?? "—"} |`);
}
void resolveAdminTab;
writeFileSync("docs/admin-v3/ADMIN-ROUTE-REDIRECTS.md", red.join("\n") + "\n");
console.log("wrote registers", counts);
