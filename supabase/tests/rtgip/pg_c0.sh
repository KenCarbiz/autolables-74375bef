#!/usr/bin/env bash
# C0 local acceptance: four separate throwaway PostgreSQL clusters on 127.0.0.1, each built FROM EMPTY,
# driven over real HTTP with the REAL new runtime code in place of the staging harness pieces
# (src/lib/rooftopos-parked/rtgip2-staging/c0-runtime.pg.test.ts).
#
#   gateway    Signal Hub at $SH_REPO: its migrations and fixtures, rtgip2.sql, reconciliation-v3.sql,
#              rooftop-registry.sql and registry-sync.sql, applied as its own scripts/acceptance applies them.
#              The registry lives on this database; its real route handlers are served over HTTP by
#              $SH_REPO/scripts/acceptance/serve-gateway.ts (started by the test file).
#   autolabels supabase/tests/rtgip/autolabels_node.sh (autolabels_node_bootstrap), staging_node.sql, seed
#   autocurb   $AC_REPO/scripts/rtgip-staging/autocurb_node.sh (autocurb_node_bootstrap + seed)
#   autoframe  $AF_REPO/scripts/rtgip-staging-node.sh with with_scope=0 -v with_connections=0, then
#              public.rtgip_sync_rooftop_scope(export rows) as rtgip_registry_sync
#
# Every app node is served by its generated rtgip2-runtime bundle under Deno (the test file injects the
# compiled gate literal and lifts the transport CHECK in these throwaway clusters only). Every seed value
# comes from the registry export views; every signing key is generated by the test and discarded with
# the clusters. Never connects to Supabase or any hosted system.
#
#   AC_REPO   AutoCurb checkout        (default /home/claude/hartecash-2edb8fec)
#   AF_REPO   AutoFrame checkout       (default /home/claude/showroom-photo-polish)
#   SH_REPO   Signal Hub checkout      (default /home/claude/rooftop-vehicle-signal-hub)
#   RTGIP_DENO  Deno 2.x binary        (default /tmp/denobin/node_modules/.bin/deno; npm i deno@2.1.4 there if missing)
#   RTGIP_BUN   bun binary             (default bun)
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
AC_REPO="${AC_REPO:-/home/claude/hartecash-2edb8fec}"
AF_REPO="${AF_REPO:-/home/claude/showroom-photo-polish}"
SH_REPO="${SH_REPO:-/home/claude/rooftop-vehicle-signal-hub}"
DENO="${RTGIP_DENO:-/tmp/denobin/node_modules/.bin/deno}"
BUN="${RTGIP_BUN:-$(command -v bun || true)}"
for need in "$AC_REPO/scripts/rtgip-staging/autocurb_node.sh" "$AF_REPO/scripts/rtgip-staging-node.sh" "$SH_REPO/scripts/acceptance/serve-gateway.ts" "$SH_REPO/docs/proposals/hosted-package/registry-sync.sql" "$DENO" "$AC_REPO/supabase/functions/_shared/rtgip2-runtime.bundle.js" "$AF_REPO/supabase/functions/_shared/rtgip2-runtime.bundle.js"; do
  [ -f "$need" ] || { echo "missing $need (set AC_REPO / AF_REPO / SH_REPO / RTGIP_DENO)"; exit 2; }
done
PGBIN="${PGBIN:-$(ls -d /usr/lib/postgresql/*/bin 2>/dev/null | sort -V | tail -1)}"
export PATH="$PGBIN:$PATH"
BASE="${RTGIP_C0_PORT:-55480}"
WORK="$(mktemp -d)"; chmod 755 "$WORK"
RUNAS=()
if [ "$(id -u)" = "0" ]; then chown postgres "$WORK"; RUNAS=(runuser -u postgres --); fi
NODES=(autolabels autocurb autoframe gateway)
cleanup() {
  for n in "${NODES[@]}"; do "${RUNAS[@]}" "$PGBIN/pg_ctl" -D "$WORK/$n" -m immediate stop >/dev/null 2>&1 || true; done
  rm -rf "$WORK"
}
trap cleanup EXIT
cp -r "$ROOT/supabase" "$WORK/sb"; chmod -R a+rX "$WORK/sb"
mkdir -p "$WORK/ac"
for d in scripts/rtgip-staging docs/rooftopos/proposed-sql supabase/migrations; do mkdir -p "$WORK/ac/$d"; cp -r "$AC_REPO/$d/." "$WORK/ac/$d/"; done
chmod -R a+rX "$WORK/ac"

i=0
for n in "${NODES[@]}"; do
  port=$((BASE + i)); i=$((i + 1))
  "${RUNAS[@]}" "$PGBIN/initdb" -D "$WORK/$n" -U postgres -A trust >/dev/null
  "${RUNAS[@]}" "$PGBIN/pg_ctl" -D "$WORK/$n" -o "-p $port -k $WORK -c listen_addresses=127.0.0.1 -c max_connections=100" -l "$WORK/$n.log" -w start >/dev/null
  "${RUNAS[@]}" "$PGBIN/createdb" -h 127.0.0.1 -p "$port" -U postgres "c0_$n"
  eval "PORT_$n=$port"
done
psql_on() { local port=$1 db=$2; shift 2; PGOPTIONS="-c client_min_messages=warning" "${RUNAS[@]}" "$PGBIN/psql" -h 127.0.0.1 -p "$port" -U postgres -d "$db" -qAtX "$@"; }
uuid() { cat /proc/sys/kernel/random/uuid; }
GW() { psql_on "$PORT_gateway" c0_gateway -v ON_ERROR_STOP=1 "$@"; }
apply_twice() {
  local port=$1 db=$2 f=$3
  psql_on "$port" "$db" -v ON_ERROR_STOP=1 -f "$f" >/dev/null 2>&1 || { psql_on "$port" "$db" -v ON_ERROR_STOP=1 -f "$f"; exit 1; }
  psql_on "$port" "$db" -v ON_ERROR_STOP=1 -f "$f" >/dev/null 2>&1 || { echo "FAIL  $f is not idempotent on $db"; exit 1; }
}
SEED="$WORK/seed.env"; : > "$SEED"
keep() { while IFS= read -r l; do echo "$l" >> "$SEED"; done; }

# ---- Gateway node: Signal Hub, built the way its scripts/acceptance build it -------------------
# Roles and auth fixtures as scripts/bootstrap-gateway-disposable.py, then its migrations in order, its
# disposable fixtures, rtgip2.sql, reconciliation-v3.sql, and per check: rooftop-registry.sql and registry-sync.sql.
GW -c "CREATE ROLE anon NOLOGIN; CREATE ROLE authenticated NOLOGIN; CREATE ROLE service_role NOLOGIN BYPASSRLS;" >/dev/null
GW -c "CREATE SCHEMA auth; CREATE SCHEMA extensions;
CREATE TABLE auth.users(id uuid PRIMARY KEY,email text,email_confirmed_at timestamptz,is_anonymous boolean DEFAULT false,aud text,role text);
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS \$\$ SELECT coalesce(nullif(current_setting('request.jwt.claim.sub',true),''),nullif(current_setting('request.jwt.claims',true),'')::jsonb->>'sub')::uuid \$\$;
GRANT USAGE ON SCHEMA auth TO anon,authenticated,service_role;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon,authenticated,service_role;" >/dev/null
GWF() { psql_on "$PORT_gateway" c0_gateway -v ON_ERROR_STOP=1 -f "$1" >/dev/null || { echo "FAIL applying $1"; exit 1; }; }
SHW="$WORK/sh"; mkdir -p "$SHW"; cp -r "$SH_REPO/drizzle" "$SH_REPO/docs" "$SH_REPO/scripts" "$SHW/"; chmod -R a+rX "$SHW"
for f in "$SHW"/drizzle/migrations/[0-9]*.sql; do GWF "$f"; done
for f in scripts/gateway-disposable-fixtures.sql docs/proposals/final-execution/rtgip2.sql docs/proposals/final-execution/reconciliation-v3.sql \
         docs/proposals/hosted-package/rooftop-registry.sql docs/proposals/hosted-package/registry-sync.sql; do GWF "$SHW/$f"; done

# Two synthetic actors: the operator proposes, a different reviewer activates.
OP="$(uuid)"; RV="$(uuid)"
T_A="$(uuid)"; T_B="$(uuid)"
GW -c "INSERT INTO rooftop_registry.settings (environment) VALUES ('staging') ON CONFLICT DO NOTHING" >/dev/null
GW -c "INSERT INTO auth.users (id, email, email_confirmed_at) VALUES ('$OP', 'op@synthetic.test', now()), ('$RV', 'rv@synthetic.test', now())" >/dev/null
AS() { printf "SET request.jwt.claims = '{\"sub\":\"%s\",\"aal\":\"aal2\"}'; SET ROLE authenticated; " "$1"; }
[ "$(GW -c "SELECT rooftop_registry.bootstrap_platform_admin('$OP', 'synthetic owner bootstrap')")" = "enrolled" ] || { echo "bootstrap failed"; exit 1; }
for t in "$T_A" "$T_B"; do
  [ "$(GW -c "$(AS "$OP")SELECT rooftop_registry.enroll_principal('$RV', 'dealership_gm', '$t', 'evidence:synthetic-gm-letter')")" = "enrolled" ] || { echo "GM enrollment failed"; exit 1; }
done
propose() { # tenant rooftop dealership_ref ac_dealership
  GW -c "$(AS "$OP")SELECT rooftop_registry.propose_rooftop('synthetic staging proposal for $2', '$1', '$2', '$3', '$1', '$(uuid)', '$4', '$(uuid)', '$(uuid)', '$(uuid)')"
}
RID_A="$(propose "$T_A" rf-stg-01 "synthetic:staging-primary" dlr-stg-01)"
RID_B="$(propose "$T_B" rf-stg-02 "synthetic:staging-second" dlr-stg-02)"
for r in "$RID_A" "$RID_B"; do
  [ "$(GW -c "$(AS "$OP")SELECT rooftop_registry.activate_rooftop('$r', 'self review attempt must fail', 'evidence:x')")" = "reviewer_is_creator" ] || { echo "registry accepted a self review"; exit 1; }
  [ "$(GW -c "$(AS "$RV")SELECT rooftop_registry.activate_rooftop('$r', 'synthetic staging reviewer sign-off', 'evidence:synthetic-dealer-letter')")" = "activated" ] || { echo "activation failed"; exit 1; }
done
{
  echo "REG_OPERATOR=$OP"; echo "REG_REVIEWER=$RV"; echo "REG_ROOFTOP_A=$RID_A"; echo "REG_ROOFTOP_B=$RID_B"
} | keep

# Export rows, by rooftop_id (primary rf-stg-01, second tenant's rf-stg-02).
col() { GW -F '|' -c "$1"; }
IFS='|' read -r AL_T AL_R AL_S < <(col "SELECT tenant_id, rooftop_id, store_id FROM rooftop_registry.export_al_rooftop_stores WHERE rooftop_id = 'rf-stg-01'")
IFS='|' read -r AL_T2 AL_R2 AL_S2 < <(col "SELECT tenant_id, rooftop_id, store_id FROM rooftop_registry.export_al_rooftop_stores WHERE rooftop_id = 'rf-stg-02'")
IFS='|' read -r AC_D AC_L AC_T AC_R < <(col "SELECT dealership_id, store_location_id, tenant_id, rooftop_id FROM rooftop_registry.export_ac_rooftop_scope WHERE rooftop_id = 'rf-stg-01'")
IFS='|' read -r AF_T AF_R AF_CT AF_CR AF_REG < <(col "SELECT af_tenant_id, af_rooftop_id, tenant_id, rooftop_id, registry_id FROM rooftop_registry.export_af_rooftop_scope WHERE rooftop_id = 'rf-stg-01'")
IFS='|' read -r AF_T2 AF_R2 AF_CT2 AF_CR2 AF_REG2 < <(col "SELECT af_tenant_id, af_rooftop_id, tenant_id, rooftop_id, registry_id FROM rooftop_registry.export_af_rooftop_scope WHERE rooftop_id = 'rf-stg-02'")
AF_EXPORT="$(col "SELECT coalesce(jsonb_agg(to_jsonb(e) ORDER BY e.rooftop_id), '[]') FROM rooftop_registry.export_af_rooftop_scope e")"

# ---- AutoLabels node ---------------------------------------------------------------------------
# shellcheck source=autolabels_node.sh
. "$ROOT/supabase/tests/rtgip/autolabels_node.sh"
P=$PORT_autolabels; D=c0_autolabels
autolabels_node_bootstrap $P $D "$WORK/sb"
apply_twice $P $D "$WORK/sb/tests/rtgip/staging_node.sql"
OUT="$(AL_SEED_DELIVER=0 AL_SEED_TENANT=$AL_T AL_SEED_OTHER_TENANT=$AL_T2 AL_SEED_STORE=$AL_S AL_SEED_ROOFTOP=$AL_R autolabels_node_seed $P $D "$WORK/sb")"
keep <<<"$OUT"; eval "$(sed 's/^/export /' <<<"$OUT")"
EP_OPEN="$AL_SEED_OPEN_EPISODE"; EP_DELIVERED="$AL_SEED_DELIVERED_EPISODE"

# Bind both episodes from their AutoLabels custody events (the registry never infers by VIN).
bind() { # episode vin
  local ev; ev="$(psql_on $PORT_autolabels c0_autolabels -c "SELECT id FROM public.vehicle_history_audit WHERE action = 'custody.episode_opened' AND entity_id = '$1'")"
  [ -n "$ev" ] || { echo "no custody event for $1"; exit 1; }
  [ "$(GW -c "SET ROLE service_role; SELECT rooftop_registry.bind_episode('$RID_A', '$1', '$1', '$2', '$ev')")" = "bound" ] || { echo "bind failed for $1"; exit 1; }
  echo "REG_LABELS_EVENT_$3=$ev" | keep
}
bind "$EP_OPEN" 1M8GDM9AXKP042801 OPEN
bind "$EP_DELIVERED" 1M8GDM9AXKP042802 DELIVERED

# ---- AutoCurb node ----------------------------------------------------------------------------
# shellcheck source=/dev/null
. "$WORK/ac/scripts/rtgip-staging/autocurb_node.sh"
P=$PORT_autocurb; D=c0_autocurb
autocurb_node_bootstrap $P $D "$WORK/ac"
OUT="$(AC_SEED_TENANT=$AC_T AC_SEED_ROOFTOP=$AC_R AC_SEED_DEALERSHIP=$AC_D AC_SEED_STORE=$AC_L autocurb_node_seed $P $D)"
keep <<<"$OUT"

# ---- AutoFrame node ---------------------------------------------------------------------------
bash "$AF_REPO/scripts/rtgip-staging-node.sh" --db "host=$WORK port=$PORT_autoframe dbname=c0_autoframe user=postgres" \
  -v tenant="$AF_T" -v rooftop="$AF_R" -v other_tenant="$AF_T2" -v other_rooftop="$AF_R2" \
  -v canon_tenant="$AF_CT" -v canon_rooftop="$AF_CR" -v canon_other_tenant="$AF_CT2" -v canon_other_rooftop="$AF_CR2" \
  -v registry_id="$AF_REG" -v other_registry_id="$AF_REG2" -v with_scope=0 -v with_connections=0
psql_on $PORT_autoframe c0_autoframe -v ON_ERROR_STOP=1 -c "SET ROLE rtgip_registry_sync; SELECT public.rtgip_sync_rooftop_scope('$AF_EXPORT'::jsonb)" >/dev/null

# The app nodes get a marker table for the atomic-capture test only (AutoLabels carries it from staging_node.sql).
for n in autocurb autoframe; do
  eval "pp=\$PORT_$n"
  apply_twice "$pp" "c0_$n" "$WORK/sb/tests/rtgip/staging_node.sql"
done

# Seed values for the test, in one JSON file.
python3 - "$SEED" "$WORK/seed.json" <<'PY'
import json, sys
d = {}
for line in open(sys.argv[1]):
    line = line.rstrip("\n")
    if "=" in line:
        k, v = line.split("=", 1)
        d[k] = v
json.dump(d, open(sys.argv[2], "w"), indent=1)
PY
chmod a+r "$WORK/seed.json"

if [ -n "${RTGIP_C0_NODES_ONLY:-}" ]; then cat "$WORK/seed.json"; exit 0; fi
echo "four clusters up (ports $PORT_autolabels-$PORT_gateway, Postgres $(psql_on $PORT_gateway c0_gateway -c 'SHOW server_version')); nodes built from empty; Gateway = Signal Hub $(git -C "$SH_REPO" rev-parse --short HEAD); registry exports drove every seed"
cd "$ROOT"
RTGIP_C0_AUTOLABELS="postgres://postgres@127.0.0.1:$PORT_autolabels/c0_autolabels" \
RTGIP_C0_AUTOCURB="postgres://postgres@127.0.0.1:$PORT_autocurb/c0_autocurb" \
RTGIP_C0_AUTOFRAME="postgres://postgres@127.0.0.1:$PORT_autoframe/c0_autoframe" \
RTGIP_C0_GATEWAY_DB="postgres://postgres@127.0.0.1:$PORT_gateway/c0_gateway" \
RTGIP_C0_SEED="$WORK/seed.json" SH_REPO="$SH_REPO" AC_REPO="$AC_REPO" AF_REPO="$AF_REPO" RTGIP_DENO="$DENO" RTGIP_BUN="$BUN" \
RTGIP_C0_REPORT="${RTGIP_C0_REPORT:-}" \
  npx vitest run --reporter=verbose --testTimeout=180000 --hookTimeout=300000 src/lib/rooftopos-parked/rtgip2-staging/c0-runtime.pg.test.ts
