  END IF;
  IF current_setting('server_version_num')::int / 10000 <> 17 THEN
    RAISE EXCEPTION 'p2al_edge_stg_stop: server major % is not 17', current_setting('server_version_num');
  END IF;
  PERFORM set_config('lock_timeout', '5s', true);
  IF obj_description(to_regclass('rtgip.evidence_v3'), 'pg_class') IS DISTINCT FROM '{"version":"AR3-APP-r1","contract":"rtgip/3-contract-freeze/1","attest":"rtgip/3-attest/1"}' THEN
