-- K5-v3 autolabels inverse: remove the rtgip/3 public key rows (TEMPLATE, PROPOSAL, NOT APPROVED).
-- autolabels PRODUCTION (Supabase onnbmmdbrsgytfozfozn, Lovable 1a2a5abf). One DO statement, atomic. Public keys only: no private key, seed or
-- secret is ever placed here. Fill p from the owner card (keyset sha256 and per-key fingerprints) and the canonical keyset
-- document, then wrap the filled text with scripts/rtgip3/gen_prod_al.py --fill-k5, which prints its own sha256 for approval.
-- STOPs unless the keyset text hashes to the card value, is canonical, is env prd with exactly four current keys (one per
-- owner) and every fingerprint is sha256(public_key) and equals the card. Removes the four rows and their binding rows; refuses once any evidence names a key.
-- Generated by scripts/rtgip3/gen_ar3.py; do not hand-edit beyond p.
DO $k5v3$
DECLARE
  p constant jsonb := '{"card_fingerprints": {"<key_id>": "<64 hex fingerprint printed on the owner card>"}, "keyset": "<the canonical rtgip/3-keyset/1 document text, byte for byte>", "keyset_sha256": "<64 hex: keyset sha256 printed on the owner card>", "status": "PENDING"}'::jsonb;
  v_text text;
  v_doc jsonb;
  k jsonb;
  v_n integer;
  v_m integer;
  v_s text;
BEGIN
  IF coalesce(host(inet_server_addr()), '') <> '2a05:d018:135e:166d:40ff:d4ff:1780:16c1' THEN
    RAISE EXCEPTION 'k5v3_al_inverse_stop: wrong server %', coalesce(host(inet_server_addr()), 'null');
  END IF;
  IF session_user <> 'postgres' OR current_user <> 'postgres' THEN
    RAISE EXCEPTION 'k5v3_al_inverse_stop: must run as postgres (session %, current %)', session_user, current_user;
  END IF;
  IF current_setting('server_version_num')::int / 10000 <> 17 THEN
    RAISE EXCEPTION 'k5v3_al_inverse_stop: server major % is not 17', current_setting('server_version_num');
  END IF;
  PERFORM set_config('lock_timeout', '5s', true);
  IF p->>'status' IS DISTINCT FROM 'FILLED' THEN RAISE EXCEPTION 'k5v3_al_inverse_stop: parameters are PENDING; fill them from the owner card'; END IF;
  SELECT local_app INTO v_s FROM rtgip.delivery_config;
  IF v_s IS DISTINCT FROM 'autolabels' THEN RAISE EXCEPTION 'k5v3_al_inverse_stop: delivery_config.local_app is %, expected autolabels', coalesce(v_s, 'null'); END IF;
  IF obj_description(to_regclass('rtgip.evidence_v3'), 'pg_class') IS DISTINCT FROM '{"version":"AR3-APP-r1","contract":"rtgip/3-contract-freeze/1","attest":"rtgip/3-attest/1"}' THEN
    RAISE EXCEPTION 'k5v3_al_inverse_stop: rtgip/3 (ar3-al.sql) is not applied';
  END IF;
  v_text := p->>'keyset';
  IF p->>'keyset_sha256' !~ '^[0-9a-f]{64}$' OR encode(sha256(convert_to(v_text, 'UTF8')), 'hex') <> p->>'keyset_sha256' THEN
    RAISE EXCEPTION 'k5v3_al_inverse_stop: keyset text sha256 % differs from the card value %', encode(sha256(convert_to(coalesce(v_text, ''), 'UTF8')), 'hex'), p->>'keyset_sha256';
  END IF;
  BEGIN v_doc := v_text::jsonb; EXCEPTION WHEN others THEN RAISE EXCEPTION 'k5v3_al_inverse_stop: keyset is not JSON'; END;
  IF rtgip.canonical_json(v_doc) IS DISTINCT FROM v_text THEN RAISE EXCEPTION 'k5v3_al_inverse_stop: keyset is not canonical JSON'; END IF;
  IF (SELECT array_agg(x ORDER BY x COLLATE "C") FROM jsonb_object_keys(v_doc) x) IS DISTINCT FROM ARRAY['env','issued_at','keys','keyset','serial']
     OR v_doc->>'keyset' IS DISTINCT FROM 'rtgip/3-keyset/1' OR v_doc->>'env' IS DISTINCT FROM 'prd'
     OR jsonb_typeof(v_doc->'serial') IS DISTINCT FROM 'number' OR jsonb_typeof(v_doc->'issued_at') IS DISTINCT FROM 'number'
     OR jsonb_typeof(v_doc->'keys') IS DISTINCT FROM 'array' THEN
    RAISE EXCEPTION 'k5v3_al_inverse_stop: keyset is not an rtgip/3-keyset/1 document for env prd';
  END IF;
  FOR k IN SELECT x FROM jsonb_array_elements(v_doc->'keys') x LOOP
    IF (SELECT array_agg(x ORDER BY x COLLATE "C") FROM jsonb_object_keys(k) x) IS DISTINCT FROM
         ARRAY['alg','connection_ids','fingerprint','key_id','not_after','not_before','owner','protocol','public_key','revoked_at','revoked_reason','status']
       OR k->>'key_id' !~ '^prd-(gateway|autolabels|autocurb|autoframe)-ed[1-9][0-9]{0,3}$'
       OR k->>'owner' IS DISTINCT FROM substring(k->>'key_id' FROM '^prd-([a-z]+)-ed')
       OR k->>'protocol' IS DISTINCT FROM 'rtgip/3' OR k->>'alg' IS DISTINCT FROM 'ed25519' OR k->>'status' IS DISTINCT FROM 'current'
       OR jsonb_typeof(k->'revoked_at') IS DISTINCT FROM 'null' OR jsonb_typeof(k->'revoked_reason') IS DISTINCT FROM 'null'
       OR k->>'public_key' !~ '^[0-9a-f]{64}$' OR k->>'fingerprint' IS DISTINCT FROM encode(sha256(decode(k->>'public_key', 'hex')), 'hex')
       OR k->>'fingerprint' IS DISTINCT FROM p->'card_fingerprints'->>(k->>'key_id')
       OR jsonb_typeof(k->'not_before') IS DISTINCT FROM 'number' OR jsonb_typeof(k->'not_after') IS DISTINCT FROM 'number'
       OR (k->>'not_after')::numeric <= (k->>'not_before')::numeric OR jsonb_typeof(k->'connection_ids') IS DISTINCT FROM 'array' THEN
      RAISE EXCEPTION 'k5v3_al_inverse_stop: key record % fails the keyset or card check', coalesce(k->>'key_id', '?');
    END IF;
  END LOOP;
  IF EXISTS (SELECT 1 FROM jsonb_array_elements(v_doc->'keys') WITH ORDINALITY a(x, i) JOIN jsonb_array_elements(v_doc->'keys') WITH ORDINALITY b(y, j)
             ON j = i + 1 WHERE NOT ((a.x->>'key_id') COLLATE "C" < (b.y->>'key_id') COLLATE "C")) THEN
    RAISE EXCEPTION 'k5v3_al_inverse_stop: keyset keys are not sorted by key_id';
  END IF;
  SELECT count(*), count(DISTINCT x->>'owner') INTO v_n, v_m FROM jsonb_array_elements(v_doc->'keys') x;
  IF v_n <> 4 OR v_m <> 4 THEN RAISE EXCEPTION 'k5v3_al_inverse_stop: keyset has % keys for % owners, expected exactly four current keys, one per owner', v_n, v_m; END IF;
  IF (SELECT array_agg(x ORDER BY x COLLATE "C") FROM jsonb_object_keys(p->'card_fingerprints') x)
     IS DISTINCT FROM (SELECT array_agg(x->>'key_id' ORDER BY x->>'key_id' COLLATE "C") FROM jsonb_array_elements(v_doc->'keys') x) THEN
    RAISE EXCEPTION 'k5v3_al_inverse_stop: card fingerprints do not name exactly the keyset key ids';
  END IF;
  IF EXISTS (SELECT 1 FROM rtgip.evidence_v3 e JOIN jsonb_array_elements(v_doc->'keys') x ON e.key_id = x->>'key_id') THEN
    RAISE EXCEPTION 'k5v3_al_inverse_stop: evidence names a keyset key; key rows are retained';
  END IF;
  SELECT count(*) INTO v_n FROM rtgip.public_keys pk WHERE NOT EXISTS (SELECT 1 FROM jsonb_array_elements(v_doc->'keys') x WHERE x->>'key_id' = pk.key_id);
  IF v_n <> 0 THEN RAISE EXCEPTION 'k5v3_al_inverse_stop: % key rows outside this keyset exist', v_n; END IF;
  DELETE FROM rtgip.public_key_bindings b USING jsonb_array_elements(v_doc->'keys') x WHERE b.key_id = x->>'key_id';
  DELETE FROM rtgip.public_keys pk USING jsonb_array_elements(v_doc->'keys') x WHERE pk.key_id = x->>'key_id';
  SELECT (SELECT count(*) FROM rtgip.public_keys) + (SELECT count(*) FROM rtgip.public_key_bindings) INTO v_n;
  IF v_n <> 0 THEN RAISE EXCEPTION 'k5v3_al_inverse_check: % key or binding rows remain', v_n; END IF;
  RAISE NOTICE 'k5v3_al_inverse_ok: 4 rtgip/3 key rows and their bindings removed';
END
$k5v3$;
