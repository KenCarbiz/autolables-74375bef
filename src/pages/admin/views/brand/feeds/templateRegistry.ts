const MONRONEY_NOTE = "A Monroney-style layout generated by AutoLabels. It is not the manufacturer's Monroney label.";

const KIND_TITLE: Record<LabelKind, TemplateEntry["documentType"]> = { window: "Window sticker", addendum: "Addendum" };

const inches = (n: number) => (Number.isInteger(n) ? String(n) : String(Number(n.toFixed(2))));

export function buildEntries(templates: readonly StudioTemplate[], archive: readonly ArchiveRow[] | null): TemplateEntry[] {
  const rows = new Map((archive ?? []).map((r) => [r.template_key, r]));
  const studio = templates.map<TemplateEntry>((t) => {
    const row = rows.get(t.config.id);
    return {
      ref: `studio:${t.config.id}`,
      id: t.config.id,
      name: t.config.name,
      source: "studio",
      version: row?.current_version != null ? `v${row.current_version}` : "Built in, not versioned",
      documentType: KIND_TITLE[t.config.type],
      kind: t.config.type,
      conditions: ["used", "new"],
      paper: `${inches(t.config.widthIn)} x ${inches(t.config.heightIn)} in`,
      availability: row && row.is_active === false ? "retired" : "available",
      origin: "dealer_label",
      template: t,
      note: /monroney|factory/i.test(`${t.config.name} ${t.config.useCase ?? ""}`) ? MONRONEY_NOTE : t.config.useCase,
    };
  });
  const builders = Object.values(LABEL_BUILDERS).map<TemplateEntry>((b) => ({
    ref: `builder:${b.key}`,
    id: b.key,
    name: b.label,
    source: "builder",
    version: "Builder, not versioned",
    documentType: KIND_TITLE[b.kind],
    kind: b.kind,
    conditions: b.conditions,
    paper: "Set by the builder",
    availability: "available",
    origin: "dealer_label",
    note: /monroney/i.test(b.label) ? MONRONEY_NOTE : undefined,
  }));
  const byRef = new Map<string, TemplateEntry>();
  for (const e of [...builders, ...studio]) byRef.set(e.ref, e);
  return [...byRef.values()];
}

export interface Compatibility { ok: boolean; reason: string | null }

export function compatibility(entry: TemplateEntry, kind: LabelKind, condition: LabelCondition): Compatibility {
  if (entry.availability === "retired") return { ok: false, reason: "Retired in the template archive. Documents already made with it are unchanged." };
  if (entry.kind !== kind) return { ok: false, reason: `This is a ${entry.documentType.toLowerCase()} layout. This slot needs a ${KIND_TITLE[kind].toLowerCase()}.` };
  if (!entry.conditions.includes(condition)) return { ok: false, reason: `Built for ${entry.conditions.join(" and ")} vehicles only. This slot is for ${condition} vehicles.` };
  return { ok: true, reason: null };
}

export type DefaultSource = "selection" | "starred" | "platform" | "none";

export interface ResolvedSlot {
  slot: LabelSlot;
  ref: string | null;
  entry: TemplateEntry | null;
  source: DefaultSource;
  state: "ok" | "missing" | "none";
}

export function resolveSlot(slot: LabelSlot, explicit: LabelDefaults, entries: readonly TemplateEntry[], legacyByKind?: Record<string, string>): ResolvedSlot {
  const ref = resolveLabelDefault(explicit, slot, legacyByKind);
  if (!ref) return { slot, ref: null, entry: null, source: "none", state: "none" };
  const entry = entries.find((e) => e.ref === ref) ?? null;
  const source: DefaultSource = explicit[slot] ? "selection" : parseLabelRef(ref)?.kind === "builder" ? "platform" : "starred";
  return { slot, ref, entry, source, state: entry ? "ok" : "missing" };
}

