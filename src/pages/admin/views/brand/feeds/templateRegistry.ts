// Read-only view of the template registries as they exist on this branch: the Sticker Studio catalog (built-in
// templates merged with the sticker_templates archive) and the dedicated builders. This module never approves,
// publishes, creates or edits a template, and it invents none.

export type Availability = "available" | "retired";
export type TemplateOrigin = "dealer_label" | "oem_reproduction";

export interface TemplateEntry {
  ref: string;
  id: string;
  name: string;
  source: "studio" | "builder";
  version: string;
  documentType: "Window sticker" | "Addendum";
  kind: LabelKind;
  conditions: LabelCondition[];
  paper: string;
  availability: Availability;
  origin: TemplateOrigin;
  template?: StudioTemplate;
  note?: string;
}

export interface ArchiveRow {
  template_key: string;
  is_active: boolean;
  current_version: number | null;
}

